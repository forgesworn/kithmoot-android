package dev.forgesworn.kithmoot.relay

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertNull
import kotlin.test.assertTrue

class RelayGateTest {

    @Test fun `an ERROR prefix is stripped before the NIP-01 prefix is read`() {
        assertEquals("rate-limited: slow down", RelayRefusal.strip("ERROR: rate-limited: slow down"))
        assertEquals("blocked: no", RelayRefusal.strip("error:blocked: no"))
        assertEquals("pow: 20 bits", RelayRefusal.strip("pow: 20 bits"))
        assertEquals(RelayRefusalKind.RATE_LIMITED, RelayRefusal.classify("ERROR: rate-limited: slow down", false))
        assertEquals(RelayRefusalKind.STOP, RelayRefusal.classify("ERROR: blocked: banned", false))
        assertEquals(RelayRefusalKind.STOP, RelayRefusal.classify("restricted: members only", false))
        assertEquals(RelayRefusalKind.STOP, RelayRefusal.classify("pow: difficulty 28", false))
        assertNull(RelayRefusal.classify("invalid: bad signature", false))
        assertNull(RelayRefusal.classify("duplicate: already have it", false))
        assertEquals("Write refused: rate limited", writeRefusal("ERROR: rate-limited: slow down"))
    }

    @Test fun `auth-required stops only when there is no grant to answer it`() {
        assertEquals(RelayRefusalKind.STOP, RelayRefusal.classify("auth-required: sign in", canAuthenticate = false))
        assertNull(RelayRefusal.classify("auth-required: sign in", canAuthenticate = true))
    }

    @Test fun `notices about rate or too many slow down, words that only contain rate do not`() {
        assertTrue(RelayRefusal.noticeAsksToSlowDown("Rate limit exceeded"))
        assertTrue(RelayRefusal.noticeAsksToSlowDown("rate-limited: too fast"))
        assertTrue(RelayRefusal.noticeAsksToSlowDown("Too many concurrent REQs"))
        assertTrue(RelayRefusal.noticeAsksToSlowDown("ratelimited"))
        assertFalse(RelayRefusal.noticeAsksToSlowDown("This relay is moderated"))
        assertFalse(RelayRefusal.noticeAsksToSlowDown("We operate under these terms"))
        assertFalse(RelayRefusal.noticeAsksToSlowDown("generated by strfry"))
    }

    @Test fun `a refused upgrade status survives the close reason`() {
        assertEquals(429, RelayRefusal.httpStatus(RelayRefusal.httpCloseReason(429)))
        assertEquals(503, RelayRefusal.httpStatus("failed: http 503"))
        assertNull(RelayRefusal.httpStatus("failed: Connection reset"))
        assertNull(RelayRefusal.httpStatus("closed: 1000 bye"))
        assertTrue(RelayRefusal.httpBacksOff(403))
        assertFalse(RelayRefusal.httpBacksOff(404))
    }

    @Test fun `holds run 60 s doubling to 30 min while refusals keep coming`() {
        val gate = RelayGate()
        val url = "wss://relay.example"
        var at = 0L
        val seen = mutableListOf<Long>()
        repeat(8) {
            gate.rateLimited(url, at)
            val held = gate.heldFor(url, at)
            seen += held
            at += held + 1 // refused again just after the hold lifts
        }
        assertEquals(listOf(60_000L, 120_000L, 240_000L, 480_000L, 960_000L, 1_800_000L, 1_800_000L, 1_800_000L), seen)
    }

    @Test fun `a hold's length of quiet starts again from a minute`() {
        val gate = RelayGate()
        val url = "wss://relay.example"
        gate.rateLimited(url, 0)
        gate.rateLimited(url, 60_001)
        assertEquals(120_000, gate.heldFor(url, 60_001))
        // The second hold lifts at 180 001; quiet for longer than it lasted.
        val later = 180_001L + 120_001L
        assertFalse(gate.isHeld(url, later))
        gate.rateLimited(url, later)
        assertEquals(60_000, gate.heldFor(url, later))
    }

    @Test fun `a burst of refusals during one hold does not lengthen it`() {
        val gate = RelayGate()
        gate.rateLimited("wss://relay.example", 0)
        gate.rateLimited("wss://relay.example", 10)
        gate.rateLimited("wss://relay.example", 20)
        assertEquals(60_000, gate.heldFor("wss://relay.example", 0))
    }

    @Test fun `one relay spelt two ways is held once`() {
        val gate = RelayGate()
        gate.rateLimited("wss://Relay.Example/", 0)
        assertTrue(gate.isHeld("wss://relay.example", 1))
        assertFalse(gate.isHeld("wss://other.example", 1))
        gate.stopEvent("wss://relay.example/", "e1")
        assertTrue(gate.eventStopped("wss://relay.example", "e1"))
        assertFalse(gate.eventStopped("wss://other.example", "e1"))
    }

    @Test fun `HTTP 429 503 and 403 hold the relay, other statuses do not`() {
        val gate = RelayGate()
        for ((index, status) in listOf(429, 503, 403).withIndex()) {
            gate.upgradeRefused("wss://r$index.example", status, 0)
            assertTrue(gate.isHeld("wss://r$index.example", 1), "$status")
        }
        gate.upgradeRefused("wss://other.example", 404, 0)
        assertFalse(gate.isHeld("wss://other.example", 1))
    }

    @Test fun `turns are one a second per relay`() {
        val gate = RelayGate()
        assertEquals(0, gate.reserveTurn("wss://relay.example", 10_000))
        assertEquals(1_000, gate.reserveTurn("wss://relay.example", 10_000))
        assertEquals(2_000, gate.reserveTurn("wss://relay.example/", 10_000))
        assertEquals(0, gate.reserveTurn("wss://other.example", 10_000))
        assertEquals(0, gate.reserveTurn("wss://relay.example", 20_000))
    }

    @Test fun `the first retry waits 1 to 2 s, and a relay that never opens is retried in minutes`() {
        val policy = RelayPolicy()
        assertEquals(1_000, policy.retryDelay(0, 0) { 0 })
        assertEquals(2_000, policy.retryDelay(0, 0) { it - 1 })
        assertEquals(31_000, policy.retryDelay(10, 5) { it - 1 })
        assertEquals(1_000 + 5 * 60 * 1000L, policy.retryDelay(10, 6) { it - 1 })
    }
}
